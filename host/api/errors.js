/**
 * 把错误对象解析成 HTTP 状态码。
 *
 * 顺序：`err.status`（抛错处显式声明）→ `err.code` 查表 →
 * message 的 `CODE:` 前缀查表 → 老式 `_REQUIRED` 文案兜底 → 500。
 */
export function statusForError(err) {
  if (Number.isFinite(Number(err?.status))) return Number(err.status);
  const code = String(err?.code || '');
  if (code && CODE_STATUS[code]) return CODE_STATUS[code];

  const msg = String(err?.message || err);
  const msgCode = /^([A-Z][A-Z0-9_]{2,})/.exec(msg)?.[1] ?? '';
  if (msgCode && CODE_STATUS[msgCode]) return CODE_STATUS[msgCode];

  if (/^BODY_TOO_LARGE/.test(msg)) return 413;
  if (/^(INVALID_\w+|BAD_JSON|FORBIDDEN_PATH|PROJECT_REQUIRED|PATH_REQUIRED)/.test(msg)) return 400;
  if (/_REQUIRED$/.test(msg)) return 400;
  return 500;
}

/**
 * 后台任务的兜底 —— 失败必须留下日志。
 *
 * 直接用 `.catch(() => {})` 会让「job 是 completed 但素材库没有」这类问题
 * 完全无迹可查：runJob 只记它自己内部的失败，归档、调度、磁盘写入的异常
 * 都在它之外。
 */
export function fireAndLog(promise, ctx, label) {
  return Promise.resolve(promise).catch((e) => {
    ctx?.logger?.warn?.(`[jiuzhang] ${label} 失败：${String(e?.message || e)}`);
  });
}
