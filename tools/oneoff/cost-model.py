# 一次性核算脚本：从实测数据反推换人线的单位成本，并核对 audio_context_length 的取值。
runs = [
    ('12s/3seg s1 ctx22', 3.75, 90, 22, 1920, 88, 401),
    ('12s/3seg s1 ctx56', 3.75, 90, 56, 1920, 224, 399),
    ('12s/3seg s2 ctx22', 6.583, 158, 22, 1920, 88, 793),
    ('12s/3seg s3 ctx22', 6.583, 158, 22, 1920, 88, 801),
    ('30s/6seg s1 ctx56', 5.167, 124, 56, 2560, 224, 552),
    ('30s/6seg s2 ctx56', 7.292, 175, 56, 2560, 224, 992),
    ('30s/6seg s3 ctx56', 7.292, 175, 56, 2560, 224, 998),
    ('30s/6seg s4 ctx56', 7.292, 175, 56, 2560, 224, 1063),
    ('30s/6seg s5 ctx56', 7.292, 175, 56, 2560, 224, 1623),
    ('30s/6seg s6 ctx56', 7.292, 175, 56, 2560, 224, 1064),
]
print('% -22s %6s %5s %8s' % ('run', 'frames', 'sec', 's/frame'))
for n, d, f, c, l, a, s in runs:
    print('%-22s %6d %5d %8.2f' % (n, f, s, s / f))

tot12 = 401 + 793 + 801
tot30 = 552 + 992 + 998 + 1063 + 1623 + 1064
print()
print('12.25s 成片: 采样 %d 帧, 交付 294 帧, 总耗时 %ds = %.1f 分钟 -> %.0f s/秒成片'
      % (90 + 158 + 158, tot12, tot12 / 60, tot12 / 12.25))
print('30.0s  成片: 采样 %d 帧, 交付 %d 帧, 总耗时 %ds = %.1f 分钟 -> %.0f s/秒成片'
      % (124 + 175 * 5, 124 + 119 * 5, tot30, tot30 / 60, tot30 / 30))
print('单位成本上升: %+.1f%%' % ((tot30 / 30) / (tot12 / 12.25) * 100 - 100))
print()
print('若 30s 沿用 12.25s 那套参数等比例外推，应为 %.0fs = %.0f 分钟'
      % (tot12 / 12.25 * 30, tot12 / 12.25 * 30 / 60))
print()
print('--- 音频上下文核对 ---')
print('40Hz audio / 24fps video = 5/3 = %.4f 步/帧' % (5 / 3))
for ctx in (22, 39, 56):
    want = round(ctx * 5 / 3)
    got = min(240, max(24, ctx * 4))
    print('  ctx=%d 帧 -> 应 %d 步音频; 代码给 ctx*4 = %d 步 -> 多 %.2fx' % (ctx, want, got, got / want))

print()
print('--- 钉住帧占目标片段的比例（污染窗口占比）---')
for label, frames, ctx in [
    ('12s/3seg ctx22 (90f 段1)', 90, 22),
    ('12s/3seg ctx56 (90f 段1)', 90, 56),
    ('12s/3seg ctx22 (158f 段2/3)', 158, 22),
    ('12s/3seg ctx56 (158f 段2/3)', 158, 56),
    ('30s/6seg ctx56 (124f 段1)', 124, 56),
    ('30s/6seg ctx56 (175f 段2-6)', 175, 56),
]:
    print('  %-30s 污染 %5.1f%%  交付 %3d 帧' % (label, ctx / frames * 100, frames - ctx))
